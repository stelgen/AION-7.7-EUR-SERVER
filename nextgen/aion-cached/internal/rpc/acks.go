// AcksAfterItemData — эмитация после RQ_LOAD_ITEM page=1 (живой порядок).
var AcksAfterItemData = []uint16{0x018, 0x01D, 0x05B}

// AcksAfterWorldReady — эмитация после C> cmd=278 (ServerReady-кадр сессии).
var AcksAfterWorldReady = []uint16{0x02F, 0x063, 0x080, 0x084, 0x08B, 0x0BD, 0x0E1, 0x0E4, 0x0EB}

// BuildAcks — собрать конкатенацию ack-кадров (S2C wire) с session-X/a.
func BuildAcks(cmds []uint16, s Session) []byte {
	var out []byte
	for _, c := range cmds {
		pl, ok := ackPayloads[c]
		if !ok {
			continue
		}
		p := make([]byte, len(pl))
		copy(p, pl)
		binary.LittleEndian.PutUint32(p[0:4], s.X)
		p[4] = s.A
		out = append(out, wire.BuildS2CCached(c, p)...) // Т40: marker 0xAF (cached-канал), НЕ 0xBB — поймано живым A/B
	}
	return out
}
