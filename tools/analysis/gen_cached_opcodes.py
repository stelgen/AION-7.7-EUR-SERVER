#!/usr/bin/env python3
"""gen_cached_opcodes.py — генерация Go-таблиц опкодов CacheD64 из profile-opcode-map.md.

Источник: nextgen/cached-ref/profile-opcode-map.md (DBProfiler .profile — живая нумерация).
Выход: nextgen/aion-cached/internal/rpc/opcodes.go (8 карт uint16→имя + константы протоколов).

Использование:
  python3 gen_cached_opcodes.py [путь-к-md] [путь-к-выходу]
"""
import re, sys, datetime

SRC_DEFAULT = 'nextgen/cached-ref/profile-opcode-map.md'
OUT_DEFAULT = 'nextgen/aion-cached/internal/rpc/opcodes.go'

# секция md -> (Go-префикс, направление, порт-канал, комментарий)
SECTIONS = {
    'DB2Server':     ('RP', 'DbToServer',   '2006', 'ответы CacheD -> Server64'),
    'Server2DB':     ('RQ', 'ServerToDb',   '2006', 'запросы Server64 -> CacheD'),
    'Log2Server':    ('LP', 'LogToServer',  '2051', 'LogServer -> ? (канал логов)'),
    'Server2Log':    ('LS', 'ServerToLog',  '2051', 'Server64 -> LogServer'),
    'IC2DB':         ('ICQ', 'ICToDb',      '2305', 'ICServer -> CacheD'),
    'DB2IC':         ('ICP', 'DbToIC',      '2305', 'CacheD -> ICServer'),
    'NPRelay2Server':('GQ', 'AdminToCache','2007', 'admin/GM -> CacheD (interactive)'),
    'Server2NPRelay':('GP', 'CacheToAdmin','2007', 'CacheD -> admin/GM'),
}

def parse(path):
    text = open(path, encoding='utf-8', errors='ignore').read()
    tables = {}
    for m in re.finditer(r'## (\w[\w ]*?)\s*\((\d+) ops\)\s*\n\n\| id \| opcode \|\n\|---\|---\|\n((?:\| \d+ \| \w+\s*\|\n)+)', text):
        name, count, body = m.group(1).strip(), int(m.group(2)), m.group(3)
        rows = re.findall(r'\| (\d+) \| (\w+)\s*\|', body)
        entries = [(int(i), op) for i, op in rows]
        assert len(entries) == count, f"{name}: {len(entries)} != {count}"
        tables[name] = entries
    return tables

def gen(tables):
    lines = [
        '// Code generated by tools/analysis/gen_cached_opcodes.py from',
        '// cached-ref/profile-opcode-map.md (DBProfiler .profile, живая нумерация). НЕ править руками.',
        f'// Regenerated: {datetime.date.today().isoformat()}. Всего опкодов: {sum(len(v) for v in tables.values())}.',
        'package rpc',
        '',
    ]
    for sec, entries in tables.items():
        prefix, direction, port, comment = SECTIONS[sec]
        goname = ''.join(w.capitalize() for w in re.split(r'(?<=[a-z])(?=[A-Z0-9])|\d+', sec) if w)
        lines.append(f'// {sec} ({len(entries)} ops): {comment}.')
        lines.append(f'const {goname}Port = "{port}"')
        lines.append(f'var {goname}Names = map[uint16]string{{')
        for i, op in entries:
            lines.append(f'\t{i}: "{op}",')
        lines.append('}')
        lines.append('')
    lines += [
        '// Name — имя опкода протокола (или "<UNK>").',
        'func Name(proto int, id uint16) string {',
        '\tvar m map[uint16]string',
        '\tswitch proto {',
    ]
    for idx, sec in enumerate(tables):
        goname = ''.join(w.capitalize() for w in re.split(r'(?<=[a-z])(?=[A-Z0-9])|\d+', sec) if w)
        lines.append(f'\tcase {idx}:')
        lines.append(f'\t\tm = {goname}Names')
    lines += ['\t}', '\tif n, ok := m[id]; ok {', '\t\treturn n', '\t}', '\treturn "<UNK>"', '}']
    return '\n'.join(lines) + '\n'

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SRC_DEFAULT
    out = sys.argv[2] if len(sys.argv) > 2 else OUT_DEFAULT
    tables = parse(src)
    total = sum(len(v) for v in tables.values())
    code = gen(tables)
    open(out, 'w', encoding='utf-8', newline='\n').write(code)
    print(f"generated {out}: {len(tables)} протоколов, {total} опкодов")

if __name__ == '__main__':
    main()