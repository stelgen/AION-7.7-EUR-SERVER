#!/usr/bin/env python3
"""gen_cached_dbprocs.py — генерация Go-слоя procs мира CacheD64 из cached-ref.

Вход (nextgen/cached-ref/):
  db-procs-world-781.txt   — 781 procs, существующих в прод-БД (REF58-сверка)
  exe-procs-789.txt        — 789 procs, на которые ссылается CacheD64.exe
  procs-missing-140.txt    — 140 procs: exe зовёт, БД НЕ имеет (multi-version dispatch)

Выход: nextgen/aion-cached/internal/db/procs.go
  - WorldProcs    map[string]ProcInfo  (781: домен + versioned)
  - ExeOnlyProcs  []string             (140 — KnownMissing: exe зовёт, БД нет)
  - DbOnlyProcs   []string             (132 — в БД есть, exe не зовёт)
  - ProcExists / IsKnownMissing / DomainOf helpers

Использование:
  python3 gen_cached_dbprocs.py [cached-ref-dir] [выходной-файл]
"""
import re, sys, datetime
from collections import Counter

SRC_DEFAULT = 'nextgen/cached-ref'
OUT_DEFAULT = 'nextgen/aion-cached/internal/db/procs.go'

VER_RE = re.compile(r'_20\d{6}$')

# Домен-эвристика по имени после aion_ (порядок = приоритет матчинга)
DOMAINS = [
    ('CharInfo',    re.compile(r'(Get|Set|Save|Put|Sync)Char(Info|Data|Stat)', re.I)),
    ('ItemEnchant', re.compile(r'ItemEnchant|Enchant|PolishPoint|MagicBox', re.I)),
    ('VendorItem',  re.compile(r'VendorItem', re.I)),
    ('Item',        re.compile(r'\bItem\b', re.I)),
    ('Guild',       re.compile(r'Guild|Pledge', re.I)),
    ('House',       re.compile(r'House|FieldHouse|InstantHouse', re.I)),
    ('Quest',       re.compile(r'Quest', re.I)),
    ('Auction',     re.compile(r'Auction', re.I)),
    ('Mail',        re.compile(r'Mail', re.I)),
    ('Buddy',       re.compile(r'Buddy', re.I)),
    ('Abyss',       re.compile(r'Abyss', re.I)),
    ('AddedService', re.compile(r'AddedService', re.I)),
    ('NPC',         re.compile(r'\bNpc\b|Spawn', re.I)),
    ('User',        re.compile(r'User', re.I)),
    ('Block',       re.compile(r'Block', re.I)),
    ('Skills',      re.compile(r'Skill|Cooltime', re.I)),
]

def domain_of(name):
    body = name[len('aion_'):]
    for dom, rx in DOMAINS:
        if rx.search(body):
            return dom
    return 'Misc'

def load(path):
    return [l.strip() for l in open(path, encoding='utf-8', errors='ignore') if l.strip()]

def gen(db, exe, miss):
    dbset, exeset, missset = set(db), set(exe), set(miss)
    dbonly = sorted(dbset - exeset)
    lines = [
        '// Code generated by tools/analysis/gen_cached_dbprocs.py from cached-ref',
        '// (db-procs-world-781.txt + exe-procs-789.txt + procs-missing-140.txt). НЕ править руками.',
        f'// Regenerated: {datetime.date.today().isoformat()}.',
        f'// WorldProcs={len(db)} (versioned={sum(1 for p in db if VER_RE.search(p))}),',
        f'// ExeOnlyProcs={len(miss)} (exe зовёт, прод-БД НЕ имеет — multi-version dispatch),',
        f'// DbOnlyProcs={len(dbonly)} (в БД есть, exe не зовёт).',
        'package db',
        '',
        '// ProcInfo — запись procs мира.',
        'type ProcInfo struct {',
        '\tDomain    string // домен-эвристика: CharInfo/ItemEnchant/Item/Guild/...',
        '\tVersioned bool   // суффикс _20XXXXXX (multi-version dispatch)',
        '}',
        '',
        '// WorldProcs — 781 procs мира (прод-БД).',
        'var WorldProcs = map[string]ProcInfo{',
    ]
    for p in sorted(dbset):
        lines.append(f'\t"{p}": {{Domain: "{domain_of(p)}", Versioned: {str(bool(VER_RE.search(p))).lower()}}},')
    lines += ['}', '', '// ExeOnlyProcs — 140 procs: CacheD64.exe ссылается, прод-БД НЕ имеет.',
              '// Наш CallWorldProc отвечает ErrProcMissing ДО SQL (поведение-маркер для A/B).',
              'var ExeOnlyProcs = []string{']
    lines += [f'\t"{p}",' for p in sorted(missset)]
    lines += ['}', '', '// DbOnlyProcs — 132 procs: в БД есть, exe не зовёт (legacy).',
              'var DbOnlyProcs = []string{']
    lines += [f'\t"{p}",' for p in dbonly]
    lines += ['}', '', '''// procSets — быстрые множества (init).
var (
\tworldSet    = map[string]ProcInfo{}
\tmissingSet  = map[string]struct{}{}
)''', '', 'func init() {', '\tfor k, v := range WorldProcs {', '\t\tworldSet[k] = v', '\t}',
              '\tfor _, p := range ExeOnlyProcs {', '\t\tmissingSet[p] = struct{}{}', '\t}', '}', '',
              '''// ProcExists — proc существует в прод-БД (781).
func ProcExists(name string) bool { _, ok := worldSet[name]; return ok }

// IsKnownMissing — exe ссылается, но прод-БД proc НЕ имеет (из 140).
func IsKnownMissing(name string) bool { _, ok := missingSet[name]; return ok }

// DomainOf — домен из инвентаря (Misc для неизвестных).
// Эвристика доменов живёт в ГЕНЕРАТОРЕ (gen_cached_dbprocs.py), не в рантайме.
func DomainOf(name string) string {
	if p, ok := worldSet[name]; ok {
		return p.Domain
	}
	return "Misc"
}''']
    return '\n'.join(lines) + '\n'

def main():
    src = sys.argv[1] if len(sys.argv) > 1 else SRC_DEFAULT
    out = sys.argv[2] if len(sys.argv) > 2 else OUT_DEFAULT
    db = load(f'{src}/db-procs-world-781.txt')
    exe = load(f'{src}/exe-procs-789.txt')
    miss = load(f'{src}/procs-missing-140.txt')
    code = gen(db, exe, miss)
    open(out, 'w', encoding='utf-8', newline='\n').write(code)
    doms = Counter(domain_of(p) for p in set(db))
    print(f"generated {out}: {len(set(db))} world / {len(set(miss))} exe-only / {len(set(db) - set(exe))} db-only")
    print("домены:", dict(doms.most_common()))

if __name__ == '__main__':
    main()